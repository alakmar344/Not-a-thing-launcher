#!/usr/bin/env python3
"""Generates the Not a Thing colour layer that sits on top of stock AOSP Launcher3.

Launcher3 colours almost every surface (all apps, folders, popups, widget picker, settings)
from the Material You tonal palette: ``@android:color/system_{accent1,accent2,accent3,
neutral1,neutral2}_{0..1000}``, i.e. colours derived from the wallpaper. Not a Thing replaces
that palette with a fixed monochrome palette plus Nothing red, keeping Google's own mapping
from palette tones to UI roles:

* every Launcher3 colour resource / colour state list / drawable that references a
  ``system_*`` tone is re-declared in the app with the same name and resource qualifier,
  pointing at ``@color/nt_<family>_<tone>`` instead;
* the fixed Material 3 baseline colours used before Android 12 (``values``/``values-night``)
  are converted to the Nothing grey (or red, for tertiary/error roles) of equal lightness.

Everything is written to app/src/main/res-launcher3-theme (committed, so the build does not need
Python). Re-run after updating third_party/aosp/launcher3 or changing PALETTE:

    python3 tools/gen_nothing_theme.py
"""
import colorsys
import os
import re
import shutil

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
L3_RES = os.path.join(ROOT, "third_party/aosp/launcher3/res")
OUT = os.path.join(ROOT, "app/src/main/res-launcher3-theme")

TONES = [0, 10, 50, 100, 200, 300, 400, 500, 600, 700, 800, 900, 1000]

# Bone-white to black greys (very slightly warm, like Nothing OS) and Nothing red.
GREY = ["#FFFFFF", "#FBFBF9", "#F4F4F2", "#E8E8E5", "#CDCDCA", "#B1B1AE", "#959593",
        "#7A7A78", "#5F5F5E", "#474746", "#2E2E2E", "#1A1A1A", "#000000"]
COOL_GREY = ["#FFFFFF", "#FAFAFA", "#F2F2F3", "#E5E5E7", "#C9C9CC", "#ADADB1", "#929296",
             "#77777B", "#5D5D61", "#454548", "#2D2D30", "#19191B", "#000000"]
RED = ["#FFFFFF", "#FFFBFA", "#FFEDEC", "#FFDAD7", "#FFB3AE", "#FF8982", "#F2554D",
       "#D71921", "#B5121A", "#8C0C12", "#64080C", "#3F0306", "#000000"]

PALETTE = {
    # Primary + secondary roles stay monochrome: Nothing uses black/white, not tinted accents.
    "accent1": GREY,
    "accent2": COOL_GREY,
    # Tertiary role is Nothing red: notification dots, "attention" states.
    "accent3": RED,
    "neutral1": GREY,
    "neutral2": COOL_GREY,
}

SYSTEM_REF = re.compile(r"@android:color/system_(accent1|accent2|accent3|neutral1|neutral2)_(\d+)")
COLOR_ENTRY = re.compile(r'<color\s+name="([^"]+)"\s*>\s*([^<]*?)\s*</color>', re.S)
HEXCOL = re.compile(r"^#([0-9A-Fa-f]{6}|[0-9A-Fa-f]{8})$")

HEADER = ("<?xml version=\"1.0\" encoding=\"utf-8\"?>\n"
          "<!-- GENERATED by tools/gen_nothing_theme.py from AOSP Launcher3 resources. Do not edit. -->\n")


def nt_ref(match):
    return f"@color/nt_{match.group(1)}_{match.group(2)}"


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(text)


def to_nothing(hex_value, name):
    """Maps a fixed baseline colour onto the Nothing palette with the same lightness."""
    digits = hex_value[1:]
    alpha = digits[:2] if len(digits) == 8 else ""
    rgb = digits[-6:]
    r, g, b = (int(rgb[i:i + 2], 16) / 255 for i in (0, 2, 4))
    _, lightness, saturation = colorsys.rgb_to_hls(r, g, b)
    if saturation < 0.12:
        return hex_value  # already neutral
    ramp = RED if ("tertiary" in name or "error" in name) else GREY

    def light(h):
        rr, gg, bb = (int(h[i:i + 2], 16) / 255 for i in (1, 3, 5))
        return colorsys.rgb_to_hls(rr, gg, bb)[1]

    best = min(ramp, key=lambda h: abs(light(h) - lightness))
    return "#" + alpha + best[1:]


def main():
    if os.path.isdir(OUT):
        shutil.rmtree(OUT)

    # 1. The palette itself.
    lines = [HEADER, "<resources>\n"]
    for family, ramp in PALETTE.items():
        for tone, value in zip(TONES, ramp):
            lines.append(f'    <color name="nt_{family}_{tone}">{value}</color>\n')
    lines.append("</resources>\n")
    write(os.path.join(OUT, "values", "nt_palette.xml"), "".join(lines))

    counts = {"colors": 0, "files": 0, "baseline": 0}
    for qualifier in sorted(os.listdir(L3_RES)):
        src_dir = os.path.join(L3_RES, qualifier)
        if not os.path.isdir(src_dir):
            continue
        is_values = qualifier == "values" or qualifier.startswith("values-")
        for fname in sorted(os.listdir(src_dir)):
            src = os.path.join(src_dir, fname)
            if not fname.endswith(".xml"):
                continue
            text = open(src, encoding="utf-8").read()
            if is_values:
                if "<color" not in text:
                    continue
                overrides = []
                for name, value in COLOR_ENTRY.findall(text):
                    if SYSTEM_REF.search(value):
                        overrides.append((name, SYSTEM_REF.sub(nt_ref, value)))
                    elif qualifier in ("values", "values-night") and HEXCOL.match(value):
                        mapped = to_nothing(value, name)
                        if mapped != value:
                            overrides.append((name, mapped))
                            counts["baseline"] += 1
                if overrides:
                    body = "".join(f'    <color name="{n}">{v}</color>\n' for n, v in overrides)
                    write(os.path.join(OUT, qualifier, "nt_" + fname),
                          HEADER + "<resources>\n" + body + "</resources>\n")
                    counts["colors"] += len(overrides)
            elif SYSTEM_REF.search(text):
                # Colour state lists, drawables and layouts: same file, Nothing palette.
                body = SYSTEM_REF.sub(nt_ref, text)
                body = re.sub(r"^<\?xml[^>]*\?>\s*", "", body)
                write(os.path.join(OUT, qualifier, fname), HEADER + body)
                counts["files"] += 1
    print(f"palette: {sum(len(r) for r in PALETTE.values())} tones; overrides: "
          f"{counts['colors']} colours ({counts['baseline']} baseline), {counts['files']} files")


if __name__ == "__main__":
    main()
