#!/usr/bin/env python3
"""Generates com.android.launcher3.Flags from AOSP's aconfig declarations.

Inside the platform build, aconfig compiles third_party/aosp/launcher3/aconfig/*.aconfig into a
Flags class backed by DeviceConfig. A standalone (Gradle) build has no aconfig toolchain, so this
emits a plain class where every flag returns its release default (false, unless overridden in
ENABLED below). Re-run after updating the vendored Launcher3 sources:

    python3 tools/gen_launcher_flags.py
"""
import glob
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ACONFIG = os.path.join(ROOT, "third_party/aosp/launcher3/aconfig")
OUT = os.path.join(ROOT, "launcher3/src/config/java/com/android/launcher3/Flags.java")

# Flags the Not a Thing build turns on (stable, user-facing improvements only).
ENABLED = {
    "enable_twoline_toggle",
    "enable_cursor_hover_states",
}


def camel(name):
    return re.sub(r"_([a-z0-9])", lambda m: m.group(1).upper(), name)


def main():
    flags = []
    for path in sorted(glob.glob(os.path.join(ACONFIG, "*.aconfig"))):
        text = open(path, encoding="utf-8").read()
        flags += re.findall(r'name:\s*"([a-z0-9_]+)"', text)
    lines = [
        "// GENERATED by tools/gen_launcher_flags.py from third_party/aosp/launcher3/aconfig. Do not edit.",
        "package com.android.launcher3;",
        "",
        "/** Static aconfig flag values for the standalone Launcher3 build. */",
        "public final class Flags {",
        "    private Flags() {}",
        "",
    ]
    for f in flags:
        lines.append(f'    public static final String FLAG_{f.upper()} = "com.android.launcher3.{f}";')
    lines.append("")
    for f in flags:
        value = "true" if f in ENABLED else "false"
        lines.append(f"    public static boolean {camel(f)}() {{ return {value}; }}")
    lines.append("}")
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")
    print(f"wrote {len(flags)} flags to {os.path.relpath(OUT, ROOT)}")


if __name__ == "__main__":
    main()
